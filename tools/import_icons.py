"""Copies the input icons Rust Shark uses from amanz's "Keyboard & Mouse Input Icons"
pack (https://amanz.itch.io/) into assets/input-icons/, shrunk to 96 px, and
generates src/icons_data.rs so they're embedded in the .exe.

Usage:  python tools/import_icons.py <extracted pack folder>
"""
import pathlib
import sys

from PIL import Image

SRC = pathlib.Path(sys.argv[1])
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "input-icons"
SIZE = 96

# HID usage code (as used in macros) -> icon base name in the pack
CODES = {}
for i, ch in enumerate("abcdefghijklmnopqrstuvwxyz"):
    CODES[0x04 + i] = f"key-{ch}"
for i, d in enumerate("123456789"):
    CODES[0x1E + i] = f"key-{d}"
CODES[0x27] = "key-0"
CODES.update({
    0x28: "key-enter", 0x29: "key-esc", 0x2A: "key-backspace", 0x2B: "key-tab", 0x2C: "key-space",
    0x2D: "key-hyphen", 0x2E: "key-equals", 0x2F: "key-bracket-open", 0x30: "key-bracket-close",
    0x31: "key-backward-slash", 0x33: "key-semi-colon", 0x34: "key-quote", 0x35: "key-tilde",
    0x36: "key-comma", 0x37: "key-dot", 0x38: "key-forward-slash", 0x39: "key-caps",
    0x46: "key-prtsc", 0x47: "key-scrlk", 0x48: "key-pause", 0x49: "key-ins", 0x4A: "key-home",
    0x4B: "key-pgup", 0x4C: "key-del", 0x4D: "key-end", 0x4E: "key-pgdn",
    0x4F: "key-arrow-right", 0x50: "key-arrow-left", 0x51: "key-arrow-down", 0x52: "key-arrow-up",
    0xE0: "key-ctrl", 0xE1: "key-shift", 0xE2: "key-alt", 0xE3: "key-windows",
    # mouse buttons (macro codes F1..F5)
    0xF1: "mouse-left", 0xF2: "mouse-right", 0xF3: "mouse-middle", 0xF4: "mouse-g1", 0xF5: "mouse-g2",
})
for n in range(1, 13):
    CODES[0x3A + n - 1] = f"key-f{n}"


def find(name):
    for sub in ("keyboard-input-icons", "mouse-input-icons"):
        p = SRC / sub / f"{name}.png"
        if p.exists():
            return p
    return None


OUT.mkdir(parents=True, exist_ok=True)
arms = []
missing = []
for code, base in sorted(CODES.items()):
    for outlined in (False, True):
        name = base + ("-outlined" if outlined else "")
        src = find(name)
        if not src:
            missing.append(name)
            continue
        im = Image.open(src).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
        im.save(OUT / f"{name}.png", optimize=True)
        arms.append(f'        (0x{code:02X}, {"true" if outlined else "false"}) => include_bytes!("../assets/input-icons/{name}.png"),')

# The pack has no icon for the X6's two top buttons (behind the wheel), so build
# them from its own art: the plain body (side buttons erased) plus two small
# buttons under the wheel, the relevant one highlighted. Codes 0xF6/0xF7 are
# UI-only (top front / top rear).
from PIL import ImageDraw


def make_top(highlight, outlined):
    base = Image.open(SRC / "mouse-input-icons" / ("mouse-g1-outlined.png" if outlined else "mouse-g1.png")).convert("RGBA")
    d = ImageDraw.Draw(base)
    d.rectangle([0, 0, 114, base.height], fill=(0, 0, 0, 0))          # remove the side buttons
    d.rounded_rectangle([212, 214, 300, 314], radius=12, fill=(0, 0, 0, 0))  # clear the strip under the wheel
    gray = (255, 255, 255, 128)
    white = (255, 255, 255, 255)
    for k, (y0, y1) in enumerate(((220, 262), (270, 312))):
        box = [228, y0, 284, y1]
        if k == highlight:
            d.rounded_rectangle(box, radius=10, fill=white)
        elif outlined:
            d.rounded_rectangle(box, radius=10, outline=gray, width=9)
        else:
            d.rounded_rectangle(box, radius=10, fill=gray)
    return base.resize((SIZE, SIZE), Image.LANCZOS)


for code, which, base_name in ((0xF6, 0, "mouse-top1"), (0xF7, 1, "mouse-top2")):
    for outlined in (False, True):
        name = base_name + ("-outlined" if outlined else "")
        make_top(which, outlined).save(OUT / f"{name}.png", optimize=True)
        arms.append(f'        (0x{code:02X}, {"true" if outlined else "false"}) => include_bytes!("../assets/input-icons/{name}.png"),')

(OUT / "CREDITS.md").write_text(
    "# Input icons\n\n"
    "Keyboard and mouse input icons by **amanz**: https://amanz.itch.io/\n"
    "(\"Keyboard & Mouse Input Icons\" pack). Resized to 96 px for Rust Shark.\n",
    encoding="utf-8",
)

rs = (
    "//! Generated by tools/import_icons.py. Input icons by amanz (https://amanz.itch.io/).\n\n"
    "/// PNG for a macro/key code; `outlined` = the outline variant (used for key releases).\n"
    "pub fn icon_png(code: u8, outlined: bool) -> Option<&'static [u8]> {\n"
    "    Some(match (code, outlined) {\n" + "\n".join(arms) + "\n        _ => return None,\n    })\n}\n"
)
(ROOT / "src" / "icons_data.rs").write_text(rs, encoding="utf-8")
print(len(arms), "icons;", "missing:", missing)
